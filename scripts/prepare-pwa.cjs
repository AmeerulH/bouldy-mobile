const { createHash } = require('node:crypto');
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const publicRoot = join(require('node:path').dirname(require.main.filename), '..', 'public');
const assets = ['/offline.html', '/icons/icon-192.png', '/icons/icon-512.png', '/icons/maskable-512.png'];
const hash = createHash('sha256');
for (const path of assets) hash.update(readFileSync(join(publicRoot, path)));
const version = hash.digest('hex').slice(0, 16);
writeFileSync(join(publicRoot, 'sw.js'), `// Generated by scripts/prepare-pwa.cjs. Public fallback assets only.
const CACHE = 'bouldy-public-${version}';
const PUBLIC = new Set(${JSON.stringify(assets)});
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll([...PUBLIC])));
  // No skipWaiting: updates wait until existing pages are closed.
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('bouldy-public-') && key !== CACHE).map(key => caches.delete(key)))));
  // No clients.claim and no forced reload while forms may contain unsaved input.
});
self.addEventListener('fetch', event => {
  const request = event.request, url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  if (PUBLIC.has(url.pathname) && !url.search) {
    event.respondWith(caches.open(CACHE).then(cache => cache.match(url.pathname)).then(hit => hit || fetch(request)));
    return;
  }
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(async () => (await (await caches.open(CACHE)).match('/offline.html')) || Response.error()));
  }
  // No other HTML, bundles, credentials, private data or command responses are cached.
});
`);
console.log(`Prepared public-only PWA fallback ${version}`);
